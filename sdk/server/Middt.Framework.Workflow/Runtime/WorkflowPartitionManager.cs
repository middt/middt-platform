    internal static IEnumerable<(string Property, string Type)> ExtractIndexedProperties(WorkflowDefinition definition)
    {
        var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        if (definition.DataSchema?["properties"] is JsonObject dataProps)
        {
            foreach (var (propName, propVal) in dataProps)
            {
                if (propVal is not JsonObject propObj || !seen.Add(propName))
                {
                    continue;
                }

                // Never create B-Tree indexes on masked fields or fields with x-index: false.
                if (propObj[JsonSchemaValidator.MaskKeyword] is not null)
                {
                    continue;
                }

                var explicitIndex = propObj[JsonSchemaValidator.IndexKeyword] is JsonValue idxVal
                    && idxVal.GetValueKind() is JsonValueKind.True or JsonValueKind.False
                    ? idxVal.GetValue<bool>()
                    : (bool?)null;

                if (explicitIndex == false)
                {
                    continue;
                }

                var type = propObj["type"]?.GetValue<string>() ?? "string";
                var isEnum = propObj["enum"] is JsonArray { Count: > 0 };
                var isSearchable = propObj[JsonSchemaValidator.SearchKeyword] switch
                {
                    JsonValue sv when sv.GetValueKind() == JsonValueKind.True => true,
                    JsonValue sv when sv.GetValueKind() == JsonValueKind.String => !string.IsNullOrWhiteSpace(sv.GetValue<string>()),
                    _ => false,
                };

                // Only create a B-Tree index when explicitly requested (x-index: true) or when the field is searchable
                // with an SQL-pushable operator (enum equality or numeric/boolean comparison).
                if (explicitIndex == true || (isSearchable && (isEnum || type is "number" or "integer" or "boolean")))
                {
                    yield return (propName, type);
                }
            }
        }
    }

    internal static (string Property, DataFilterOp Op) ParseFilterKey(string rawKey)
    {
        ReadOnlySpan<(string Suffix, DataFilterOp Op)> suffixes =
        [
            ("_min", DataFilterOp.Gte),
            ("_gte", DataFilterOp.Gte),
            (".min", DataFilterOp.Gte),
            (".gte", DataFilterOp.Gte),
            ("_from", DataFilterOp.Gte),
            (".from", DataFilterOp.Gte),
            ("_max", DataFilterOp.Lte),
            ("_lte", DataFilterOp.Lte),
            (".max", DataFilterOp.Lte),
            (".lte", DataFilterOp.Lte),
            ("_to", DataFilterOp.Lte),
            (".to", DataFilterOp.Lte),
            ("_gt", DataFilterOp.Gt),
            (".gt", DataFilterOp.Gt),
            ("_lt", DataFilterOp.Lt),
            (".lt", DataFilterOp.Lt),
        ];

        foreach (var (suffix, op) in suffixes)
        {
            if (rawKey.Length > suffix.Length && rawKey.EndsWith(suffix, StringComparison.OrdinalIgnoreCase))
            {
                return (rawKey[..^suffix.Length], op);
            }
        }

        return (rawKey, DataFilterOp.Default);
    }

    internal static bool IsCreatedFromKey(string key) =>
        string.Equals(key, "createdFrom", StringComparison.OrdinalIgnoreCase) ||
        string.Equals(key, "createdAt_from", StringComparison.OrdinalIgnoreCase) ||
        string.Equals(key, "createdAt_min", StringComparison.OrdinalIgnoreCase) ||
        string.Equals(key, "createdAt_gte", StringComparison.OrdinalIgnoreCase) ||
        string.Equals(key, "createdAt.from", StringComparison.OrdinalIgnoreCase) ||
        string.Equals(key, "createdAt.min", StringComparison.OrdinalIgnoreCase);

    internal static bool IsCreatedToKey(string key) =>
        string.Equals(key, "createdTo", StringComparison.OrdinalIgnoreCase) ||
        string.Equals(key, "createdAt_to", StringComparison.OrdinalIgnoreCase) ||
        string.Equals(key, "createdAt_max", StringComparison.OrdinalIgnoreCase) ||
        string.Equals(key, "createdAt_lte", StringComparison.OrdinalIgnoreCase) ||
        string.Equals(key, "createdAt.to", StringComparison.OrdinalIgnoreCase) ||
        string.Equals(key, "createdAt.max", StringComparison.OrdinalIgnoreCase);

    internal static bool TryParseDateBound(string? raw, bool inclusiveEndOfDay, out DateTime utc)
    {
        utc = default;
        if (string.IsNullOrWhiteSpace(raw))
        {
            return false;
        }

        var trimmed = raw.Trim();
        var isDateOnly = !trimmed.Contains('T', StringComparison.OrdinalIgnoreCase) && !trimmed.Contains(':', StringComparison.Ordinal);

        if (DateTime.TryParseExact(trimmed, ["yyyy-MM-dd", "dd.MM.yyyy"], CultureInfo.InvariantCulture, DateTimeStyles.AssumeUniversal | DateTimeStyles.AdjustToUniversal, out var exactDate))
        {
            utc = inclusiveEndOfDay
                ? DateTime.SpecifyKind(exactDate.Date.AddDays(1).AddTicks(-1), DateTimeKind.Utc)
                : DateTime.SpecifyKind(exactDate.Date, DateTimeKind.Utc);
            return true;
        }

        if (DateTimeOffset.TryParse(trimmed, CultureInfo.InvariantCulture, DateTimeStyles.AssumeUniversal, out var dto))
        {
            var utcDt = dto.UtcDateTime;
            if (inclusiveEndOfDay && (isDateOnly || utcDt.TimeOfDay == TimeSpan.Zero))
            {
                utc = DateTime.SpecifyKind(utcDt.Date.AddDays(1).AddTicks(-1), DateTimeKind.Utc);
            }
            else
            {
                utc = DateTime.SpecifyKind(utcDt, DateTimeKind.Utc);
            }

            return true;
        }

        return false;
    }

    internal static bool TryParseDecimal(string? raw, out decimal number)
    {
        number = default;
        if (string.IsNullOrWhiteSpace(raw))
        {
            return false;
        }

        var normalized = raw.Trim().Replace(',', '.');
        return decimal.TryParse(normalized, NumberStyles.Float, CultureInfo.InvariantCulture, out number);
    }

    internal static bool TryGetNodeDecimal(JsonNode? node, out decimal number)
    {
        number = default;
        if (node is not JsonValue val)
        {
            return false;
        }

        if (val.GetValueKind() == JsonValueKind.Number)
        {
            if (val.TryGetValue<decimal>(out number))
            {
                return true;
            }

            return decimal.TryParse(val.ToJsonString(), NumberStyles.Float, CultureInfo.InvariantCulture, out number);
        }

        return val.GetValueKind() == JsonValueKind.String && TryParseDecimal(val.GetValue<string>(), out number);
    }

    internal static string FoldTurkishLower(string value) =>
        value
            .Replace('İ', 'i')
            .Replace('I', 'ı')
            .Replace('Ş', 'ş')
            .Replace('Ğ', 'ğ')
            .Replace('Ü', 'ü')
            .Replace('Ö', 'ö')
            .Replace('Ç', 'ç')
            .ToLowerInvariant();

    private static string FoldTurkishLowerSql(string rawTextExpr) =>
        $"LOWER(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE({rawTextExpr}, 'İ', 'i'), 'I', 'ı'), 'Ş', 'ş'), 'Ğ', 'ğ'), 'Ü', 'ü'), 'Ö', 'ö'), 'Ç', 'ç'))";

    private static string ToSqlComparisonOp(DataFilterOp op) =>
        op switch
        {
            DataFilterOp.Gte => ">=",
            DataFilterOp.Lte => "<=",
            DataFilterOp.Gt => ">",
            DataFilterOp.Lt => "<",
            _ => "=",
        };

    internal static bool IsPropertySortableAndUnmasked(string propName, JsonObject? projectedSchema, JsonObject? rawSchema)
    {
        if (!SafeIdRegex.IsMatch(propName))
        {
            return false;
        }

        if (rawSchema?["properties"] is JsonObject rawProps && rawProps.ContainsKey(propName) &&
            projectedSchema?["properties"] is JsonObject projProps && !projProps.ContainsKey(propName))
        {
            return false;
        }

        if (projectedSchema?["properties"] is JsonObject properties &&
            properties[propName] is JsonObject propSchema &&
            propSchema[JsonSchemaValidator.MaskKeyword] is not null)
        {
            return false;
        }

        return true;
    }

    /// <summary>
    /// Classifies data property filters into SQL conditions pushed to <c>WorkflowInstanceData</c> before pagination,
    /// and reports any invalid or unsupported filter keys so callers never silently return incomplete results.
    /// </summary>
    internal static (List<SqlDataCondition> SqlConditions, List<string> UnsupportedFilters, DateTime? CreatedFromUtc, DateTime? CreatedToUtc) ClassifyDataFilters(
        IReadOnlyDictionary<string, string?>? rawFilters,
        JsonObject? projectedSchema,
        JsonObject? rawSchema = null)
    {
        var sqlConditions = new List<SqlDataCondition>();
        var unsupported = new List<string>();
        DateTime? createdFromUtc = null;
        DateTime? createdToUtc = null;

        if (rawFilters is null || rawFilters.Count == 0)
        {
            return (sqlConditions, unsupported, createdFromUtc, createdToUtc);
        }

        var properties = projectedSchema?["properties"] as JsonObject;
        var rawProperties = rawSchema?["properties"] as JsonObject;

        foreach (var (rawKey, rawValue) in rawFilters)
        {
            var key = rawKey?.Trim();
            var value = rawValue?.Trim();
            if (string.IsNullOrEmpty(key) || string.IsNullOrEmpty(value))
            {
                continue;
            }

            if (IsCreatedFromKey(key))
            {
                if (TryParseDateBound(value, inclusiveEndOfDay: false, out var from))
                {
                    createdFromUtc = from;
                }
                else
                {
                    unsupported.Add(key);
                }

                continue;
            }

            if (IsCreatedToKey(key))
            {
                if (TryParseDateBound(value, inclusiveEndOfDay: true, out var to))
                {
                    createdToUtc = to;
                }
                else
                {
                    unsupported.Add(key);
                }

                continue;
            }

            var (propName, op) = ParseFilterKey(key);
            if (!SafeIdRegex.IsMatch(propName))
            {
                unsupported.Add(key);
                continue;
            }

            if (rawProperties is not null && rawProperties.ContainsKey(propName) &&
                properties is not null && !properties.ContainsKey(propName))
            {
                unsupported.Add(key);
                continue;
            }

            if (properties?[propName] is JsonObject propSchema)
            {
                if (propSchema[JsonSchemaValidator.MaskKeyword] is not null)
                {
                    unsupported.Add(key);
                    continue;
                }

                var enumArray = propSchema["enum"] as JsonArray;
                var isEnum = enumArray is { Count: > 0 };
                var propType = propSchema["type"]?.GetValue<string>() ?? "string";
                var propFormat = propSchema["format"]?.GetValue<string>();
                var isNumeric = propType is "number" or "integer";

                if (isEnum && op == DataFilterOp.Default)
                {
                    var canonical = value;
                    var foldedTarget = FoldTurkishLower(value);
                    foreach (var enumNode in enumArray!)
                    {
                        if (enumNode is JsonValue ev && ev.GetValueKind() == JsonValueKind.String)
                        {
                            var enumText = ev.GetValue<string>();
                            if (string.Equals(enumText, value, StringComparison.OrdinalIgnoreCase) ||
                                string.Equals(FoldTurkishLower(enumText), foldedTarget, StringComparison.Ordinal))
                            {
                                canonical = enumText;
                                break;
                            }
                        }
                    }

                    sqlConditions.Add(new SqlDataCondition(propName, "=", SqlConditionKind.ExactText, canonical));
                    continue;
                }

                if (isNumeric)
                {
                    if (TryParseDecimal(value, out var decValue))
                    {
                        sqlConditions.Add(new SqlDataCondition(propName, ToSqlComparisonOp(op), SqlConditionKind.Numeric, decValue));
                    }
                    else
                    {
                        unsupported.Add(key);
                    }

                    continue;
                }

                if (propType == "boolean")
                {
                    if (op == DataFilterOp.Default && bool.TryParse(value, out var boolVal))
                    {
                        sqlConditions.Add(new SqlDataCondition(propName, "=", SqlConditionKind.Boolean, boolVal));
                    }
                    else
                    {
                        unsupported.Add(key);
                    }

                    continue;
                }

                if (op is DataFilterOp.Gte or DataFilterOp.Lte or DataFilterOp.Gt or DataFilterOp.Lt || propFormat is "date" or "date-time")
                {
                    if (TryParseDateBound(value, inclusiveEndOfDay: op == DataFilterOp.Lte, out var dtBound))
                    {
                        var iso = value.Contains('T', StringComparison.OrdinalIgnoreCase) || value.Contains(':', StringComparison.Ordinal)
                            ? dtBound.ToString("O", CultureInfo.InvariantCulture)
                            : dtBound.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture);
                        sqlConditions.Add(new SqlDataCondition(propName, ToSqlComparisonOp(op), SqlConditionKind.DateBound, iso));
                    }
                    else if (TryParseDecimal(value, out var decFallback))
                    {
                        sqlConditions.Add(new SqlDataCondition(propName, ToSqlComparisonOp(op), SqlConditionKind.Numeric, decFallback));
                    }
                    else
                    {
                        unsupported.Add(key);
                    }

                    continue;
                }

                sqlConditions.Add(new SqlDataCondition(propName, "CONTAINS", SqlConditionKind.ContainsText, FoldTurkishLower(value)));
            }
            else
            {
                if (op is DataFilterOp.Gte or DataFilterOp.Lte or DataFilterOp.Gt or DataFilterOp.Lt)
                {
                    var looksLikeDate = value.Contains('-', StringComparison.Ordinal) && !value.StartsWith('-') || value.Contains('.', StringComparison.Ordinal) && value.Split('.').Length == 3;
                    if (!looksLikeDate && TryParseDecimal(value, out var decVal))
                    {
                        sqlConditions.Add(new SqlDataCondition(propName, ToSqlComparisonOp(op), SqlConditionKind.Numeric, decVal));
                    }
                    else if (TryParseDateBound(value, inclusiveEndOfDay: op == DataFilterOp.Lte, out var dtBound))
                    {
                        var iso = value.Contains('T', StringComparison.OrdinalIgnoreCase) || value.Contains(':', StringComparison.Ordinal)
                            ? dtBound.ToString("O", CultureInfo.InvariantCulture)
                            : dtBound.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture);
                        sqlConditions.Add(new SqlDataCondition(propName, ToSqlComparisonOp(op), SqlConditionKind.DateBound, iso));
                    }
                    else
                    {
                        unsupported.Add(key);
                    }
                }
                else
                {
                    sqlConditions.Add(new SqlDataCondition(propName, "CONTAINS", SqlConditionKind.ContainsText, FoldTurkishLower(value)));
                }
            }
        }

        return (sqlConditions, unsupported, createdFromUtc, createdToUtc);
    }

    /// <summary>Returns <see langword="true"/> when the provider has native SQL JSON filter &amp; sort pushdown (PostgreSQL, SQLite, SQL Server, MySQL, Oracle).</summary>
    internal static bool SupportsSqlDataPushdown(string? providerName)
    {
        if (string.IsNullOrEmpty(providerName))
        {
            return false;
        }

        return providerName.Contains("Npgsql", StringComparison.OrdinalIgnoreCase)
            || providerName.Contains("Sqlite", StringComparison.OrdinalIgnoreCase)
            || providerName.Contains("SqlServer", StringComparison.OrdinalIgnoreCase)
            || providerName.Contains("MySql", StringComparison.OrdinalIgnoreCase)
            || providerName.Contains("Oracle", StringComparison.OrdinalIgnoreCase);
    }

    /// <summary>
    /// Pushes <c>CreatedAt</c> date bounds, exact-match <c>enum</c> filters, numeric/date/boolean comparisons, and
    /// Turkish case-insensitive substring filters down to SQL before pagination.
    /// </summary>
    internal static IQueryable<WorkflowInstance> ApplySqlDataFilters(
        IQueryable<WorkflowInstance> query,
        WorkflowDbContext db,
        string? schema,
        string? workflowKey,
        IReadOnlyList<SqlDataCondition> sqlConditions,
        DateTime? createdFromUtc,
        DateTime? createdToUtc)
    {
        if (createdFromUtc is { } fromUtc)
        {
            query = query.Where(i => i.CreatedAt >= fromUtc);
        }

        if (createdToUtc is { } toUtc)
        {
            query = query.Where(i => i.CreatedAt <= toUtc);
        }

        if (sqlConditions.Count == 0)
        {
            return query;
        }

        var (sql, parameters) = BuildSqlDataFilterQuery(db.Database.ProviderName, schema, workflowKey, sqlConditions);
        if (sql is null)
        {
            return query;
        }

#pragma warning disable EF1002
        var matchingData = db.InstanceData.FromSqlRaw(sql, [.. parameters]);
#pragma warning restore EF1002
        return query.Where(i => matchingData.Any(d => d.InstanceId == i.Id && d.WorkflowKey == i.WorkflowKey));
    }

    internal static (string? Sql, List<object> Parameters) BuildSqlDataFilterQuery(
        string? providerName,
        string? schema,
        string? workflowKey,
        IReadOnlyList<SqlDataCondition> sqlConditions)
    {
        var provider = providerName ?? string.Empty;
        var isPostgres = provider.Contains("Npgsql", StringComparison.OrdinalIgnoreCase);
        var isSqlite = provider.Contains("Sqlite", StringComparison.OrdinalIgnoreCase);
        var isSqlServer = provider.Contains("SqlServer", StringComparison.OrdinalIgnoreCase);
        var isMySql = provider.Contains("MySql", StringComparison.OrdinalIgnoreCase);
        var isOracle = provider.Contains("Oracle", StringComparison.OrdinalIgnoreCase);
        if (!isPostgres && !isSqlite && !isSqlServer && !isMySql && !isOracle)
        {
            return (null, []);
        }

        var table = ResolveInstanceDataTableSql(schema, isPostgres, isSqlServer, isMySql);
        var wfKeyCol = QuoteColumn("WorkflowKey", isSqlServer, isMySql);
        var parameters = new List<object>();
        var clauses = new List<string>(sqlConditions.Count + 1);
        if (!string.IsNullOrWhiteSpace(workflowKey))
        {
            parameters.Add(workflowKey);
            clauses.Add($"{wfKeyCol} = {{0}}");
        }

        foreach (var cond in sqlConditions)
        {
            if (!SafeIdRegex.IsMatch(cond.Property))
            {
                continue;
            }

            var idx = parameters.Count;
            switch (cond.Kind)
            {
                case SqlConditionKind.Numeric:
                {
                    parameters.Add(isSqlite ? Convert.ToDouble(cond.Parameter, CultureInfo.InvariantCulture) : cond.Parameter);
                    var expr = isPostgres
                        ? $"((((\"Data\"->>'{cond.Property}')::numeric))) {cond.SqlOp} {{{idx}}}"
                        : isSqlServer
                            ? $"TRY_CAST(JSON_VALUE([Data], '$.{cond.Property}') AS decimal(38,10)) {cond.SqlOp} {{{idx}}}"
                            : isMySql
                                ? $"CAST(JSON_UNQUOTE(JSON_EXTRACT(`Data`, '$.{cond.Property}')) AS DECIMAL(38,10)) {cond.SqlOp} {{{idx}}}"
                                : isOracle
                                    ? $"TO_NUMBER(JSON_VALUE(\"Data\", '$.{cond.Property}') DEFAULT NULL ON CONVERSION ERROR) {cond.SqlOp} {{{idx}}}"
                                    : $"CAST(json_extract(\"Data\", '$.{cond.Property}') AS REAL) {cond.SqlOp} {{{idx}}}";
                    clauses.Add(expr);
                    break;
                }
                case SqlConditionKind.Boolean:
                {
                    var boolVal = (bool)cond.Parameter;
                    if (isPostgres)
                    {
                        parameters.Add(boolVal);
                        clauses.Add($"((((\"Data\"->>'{cond.Property}')::boolean))) = {{{idx}}}");
                    }
                    else if (isSqlite)
                    {
                        parameters.Add(boolVal ? 1 : 0);
                        clauses.Add($"json_extract(\"Data\", '$.{cond.Property}') = {{{idx}}}");
                    }
                    else if (isSqlServer)
                    {
                        parameters.Add(boolVal ? "true" : "false");
                        clauses.Add($"LOWER(JSON_VALUE([Data], '$.{cond.Property}')) = {{{idx}}}");
                    }
                    else if (isMySql)
                    {
                        parameters.Add(boolVal ? "true" : "false");
                        clauses.Add($"LOWER(JSON_UNQUOTE(JSON_EXTRACT(`Data`, '$.{cond.Property}'))) = {{{idx}}}");
                    }
                    else
                    {
                        parameters.Add(boolVal ? "true" : "false");
                        clauses.Add($"LOWER(JSON_VALUE(\"Data\", '$.{cond.Property}')) = {{{idx}}}");
                    }

                    break;
                }
                case SqlConditionKind.DateBound:
                {
                    parameters.Add(cond.Parameter);
                    var expr = isPostgres
                        ? $"((\"Data\"->>'{cond.Property}')::text) {cond.SqlOp} {{{idx}}}"
                        : isSqlServer
                            ? $"JSON_VALUE([Data], '$.{cond.Property}') {cond.SqlOp} {{{idx}}}"
                            : isMySql
                                ? $"JSON_UNQUOTE(JSON_EXTRACT(`Data`, '$.{cond.Property}')) {cond.SqlOp} {{{idx}}}"
                                : isOracle
                                    ? $"JSON_VALUE(\"Data\", '$.{cond.Property}') {cond.SqlOp} {{{idx}}}"
                                    : $"CAST(json_extract(\"Data\", '$.{cond.Property}') AS TEXT) {cond.SqlOp} {{{idx}}}";
                    clauses.Add(expr);
                    break;
                }
                case SqlConditionKind.ContainsText:
                {
                    parameters.Add(cond.Parameter);
                    var rawTextExpr = isPostgres
                        ? $"(\"Data\"->>'{cond.Property}')"
                        : isSqlServer
                            ? $"JSON_VALUE([Data], '$.{cond.Property}')"
                            : isMySql
                                ? $"JSON_UNQUOTE(JSON_EXTRACT(`Data`, '$.{cond.Property}'))"
                                : isOracle
                                    ? $"JSON_VALUE(\"Data\", '$.{cond.Property}')"
                                    : $"CAST(json_extract(\"Data\", '$.{cond.Property}') AS TEXT)";
                    var foldedExpr = FoldTurkishLowerSql(rawTextExpr);
                    var expr = isPostgres
                        ? $"STRPOS({foldedExpr}, {{{idx}}}) > 0"
                        : isSqlServer
                            ? $"CHARINDEX({{{idx}}}, {foldedExpr}) > 0"
                            : isMySql
                                ? $"LOCATE({{{idx}}}, {foldedExpr}) > 0"
                                : $"INSTR({foldedExpr}, {{{idx}}}) > 0";
                    clauses.Add(expr);
                    break;
                }
                default:
                {
                    parameters.Add(cond.Parameter);
                    var expr = isPostgres
                        ? $"((\"Data\"->>'{cond.Property}')::text) {cond.SqlOp} {{{idx}}}"
                        : isSqlServer
                            ? $"JSON_VALUE([Data], '$.{cond.Property}') {cond.SqlOp} {{{idx}}}"
                            : isMySql
                                ? $"JSON_UNQUOTE(JSON_EXTRACT(`Data`, '$.{cond.Property}')) {cond.SqlOp} {{{idx}}}"
                                : isOracle
                                    ? $"JSON_VALUE(\"Data\", '$.{cond.Property}') {cond.SqlOp} {{{idx}}}"
                                    : $"json_extract(\"Data\", '$.{cond.Property}') {cond.SqlOp} {{{idx}}}";
                    clauses.Add(expr);
                    break;
                }
            }
        }

        if (clauses.Count == 0)
        {
            return (null, []);
        }

        return ($"SELECT * FROM {table} WHERE {string.Join(" AND ", clauses)}", parameters);
    }

    /// <summary>
    /// Orders <paramref name="query"/> in the database by a JSON <c>Data</c> property before pagination, using
    /// numeric comparison for JSON numbers, Turkish case-insensitive comparison for strings, and <c>InstanceId</c>
    /// as a deterministic secondary tie-breaker.
    /// </summary>
    internal static IQueryable<WorkflowInstance> OrderBySqlDataProperty(
        IQueryable<WorkflowInstance> query,
        WorkflowDbContext db,
        string? schema,
        string? workflowKey,
        string sortProperty,
        bool ascending)
    {
        if (!SafeIdRegex.IsMatch(sortProperty))
        {
            throw new ArgumentException($"Invalid sort property '{sortProperty}'.", nameof(sortProperty));
        }

        var (sql, parameters) = BuildOrderBySqlDataQuery(db.Database.ProviderName, schema, workflowKey, sortProperty, ascending);
        if (sql is null)
        {
            return ascending
                ? query.OrderBy(i => i.CreatedAt).ThenBy(i => i.Id)
                : query.OrderByDescending(i => i.CreatedAt).ThenByDescending(i => i.Id);
        }

#pragma warning disable EF1002
        var rankedData = db.InstanceData.FromSqlRaw(sql, parameters).AsNoTracking();
#pragma warning restore EF1002
        return from i in query
               join d in rankedData on new { Id = i.Id, i.WorkflowKey } equals new { Id = d.InstanceId, d.WorkflowKey }
               orderby d.DataVersion ascending
               select i;
    }

    internal static (string? Sql, object[] Parameters) BuildOrderBySqlDataQuery(
        string? providerName,
        string? schema,
        string? workflowKey,
        string sortProperty,
        bool ascending)
    {
        var provider = providerName ?? string.Empty;
        var isPostgres = provider.Contains("Npgsql", StringComparison.OrdinalIgnoreCase);
        var isSqlite = provider.Contains("Sqlite", StringComparison.OrdinalIgnoreCase);
        var isSqlServer = provider.Contains("SqlServer", StringComparison.OrdinalIgnoreCase);
        var isMySql = provider.Contains("MySql", StringComparison.OrdinalIgnoreCase);
        var isOracle = provider.Contains("Oracle", StringComparison.OrdinalIgnoreCase);
        if (!isPostgres && !isSqlite && !isSqlServer && !isMySql && !isOracle)
        {
            return (null, []);
        }

        var table = ResolveInstanceDataTableSql(schema, isPostgres, isSqlServer, isMySql);
        var dir = ascending ? "ASC" : "DESC";
        var invDir = ascending ? "DESC" : "ASC";
        string orderByClause;
        if (isPostgres)
        {
            orderByClause = $"""
                CASE
                    WHEN jsonb_typeof("Data"->'{sortProperty}') = 'number' THEN 0
                    WHEN "Data"->'{sortProperty}' IS NULL OR jsonb_typeof("Data"->'{sortProperty}') = 'null' THEN 2
                    ELSE 1
                END ASC,
                CASE
                    WHEN jsonb_typeof("Data"->'{sortProperty}') = 'number' THEN (("Data"->>'{sortProperty}')::numeric)
                END {dir},
                {FoldTurkishLowerSql($"(\"Data\"->>'{sortProperty}')")} {dir},
                "InstanceId" {dir}
                """;
        }
        else if (isSqlServer)
        {
            orderByClause = $"""
                CASE
                    WHEN TRY_CAST(JSON_VALUE([Data], '$.{sortProperty}') AS decimal(38,10)) IS NOT NULL THEN 0
                    WHEN JSON_VALUE([Data], '$.{sortProperty}') IS NULL THEN 2
                    ELSE 1
                END ASC,
                TRY_CAST(JSON_VALUE([Data], '$.{sortProperty}') AS decimal(38,10)) {dir},
                {FoldTurkishLowerSql($"JSON_VALUE([Data], '$.{sortProperty}')")} {dir},
                [InstanceId] {dir}
                """;
        }
        else if (isMySql)
        {
            orderByClause = $"""
                CASE
                    WHEN JSON_TYPE(JSON_EXTRACT(`Data`, '$.{sortProperty}')) IN ('INTEGER', 'DOUBLE', 'DECIMAL') THEN 0
                    WHEN JSON_EXTRACT(`Data`, '$.{sortProperty}') IS NULL OR JSON_TYPE(JSON_EXTRACT(`Data`, '$.{sortProperty}')) = 'NULL' THEN 2
                    ELSE 1
                END ASC,
                CASE
                    WHEN JSON_TYPE(JSON_EXTRACT(`Data`, '$.{sortProperty}')) IN ('INTEGER', 'DOUBLE', 'DECIMAL') THEN CAST(JSON_UNQUOTE(JSON_EXTRACT(`Data`, '$.{sortProperty}')) AS DECIMAL(38,10))
                END {dir},
                {FoldTurkishLowerSql($"JSON_UNQUOTE(JSON_EXTRACT(`Data`, '$.{sortProperty}'))")} {dir},
                `InstanceId` {dir}
                """;
        }
        else if (isOracle)
        {
            orderByClause = $"""
                CASE
                    WHEN TO_NUMBER(JSON_VALUE("Data", '$.{sortProperty}') DEFAULT NULL ON CONVERSION ERROR) IS NOT NULL THEN 0
                    WHEN JSON_VALUE("Data", '$.{sortProperty}') IS NULL THEN 2
                    ELSE 1
                END ASC,
                TO_NUMBER(JSON_VALUE("Data", '$.{sortProperty}') DEFAULT NULL ON CONVERSION ERROR) {dir},
                {FoldTurkishLowerSql($"JSON_VALUE(\"Data\", '$.{sortProperty}')")} {dir},
                "InstanceId" {dir}
                """;
        }
        else
        {
            orderByClause = $"""
                CASE
                    WHEN json_type("Data", '$.{sortProperty}') IN ('integer', 'real') THEN 0
                    WHEN json_type("Data", '$.{sortProperty}') IS NULL THEN 2
                    ELSE 1
                END ASC,
                CASE
                    WHEN json_type("Data", '$.{sortProperty}') IN ('integer', 'real') THEN CAST(json_extract("Data", '$.{sortProperty}') AS REAL)
                END {dir},
                CASE
                    WHEN json_type("Data", '$.{sortProperty}') IN ('integer', 'real') AND CAST(json_extract("Data", '$.{sortProperty}') AS REAL) >= 0
                    THEN CAST(json_extract("Data", '$.{sortProperty}') AS TEXT)
                END {dir},
                CASE
                    WHEN json_type("Data", '$.{sortProperty}') IN ('integer', 'real') AND CAST(json_extract("Data", '$.{sortProperty}') AS REAL) < 0
                    THEN CAST(json_extract("Data", '$.{sortProperty}') AS TEXT)
                END {invDir},
                {FoldTurkishLowerSql($"CAST(json_extract(\"Data\", '$.{sortProperty}') AS TEXT)")} {dir},
                "InstanceId" {dir}
                """;
        }

        var cols = string.Join(", ",
            QuoteColumn("InstanceId", isSqlServer, isMySql),
            QuoteColumn("WorkflowKey", isSqlServer, isMySql),
            QuoteColumn("Data", isSqlServer, isMySql),
            QuoteColumn("DataHash", isSqlServer, isMySql),
            QuoteColumn("ETag", isSqlServer, isMySql),
            QuoteColumn("UpdatedAt", isSqlServer, isMySql));
        var dataVersionCol = QuoteColumn("DataVersion", isSqlServer, isMySql);
        var wfKeyCol = QuoteColumn("WorkflowKey", isSqlServer, isMySql);
        var intType = isMySql ? "SIGNED" : isOracle ? "NUMBER(10)" : "int";

        if (!string.IsNullOrWhiteSpace(workflowKey))
        {
            var sql = $$"""
                SELECT {{cols}},
                       CAST(ROW_NUMBER() OVER (ORDER BY {{orderByClause}}) AS {{intType}}) AS {{dataVersionCol}}
                FROM {{table}}
                WHERE {{wfKeyCol}} = {0}
                """;
            return (sql, [workflowKey]);
        }
        else
        {
            var sql = $"""
                SELECT {cols},
                       CAST(ROW_NUMBER() OVER (ORDER BY {orderByClause}) AS {intType}) AS {dataVersionCol}
                FROM {table}
                """;
            return (sql, []);
        }
    }

    private static string ResolveInstanceDataTableSql(string? schema, bool isPostgres, bool isSqlServer, bool isMySql)
    {
        if (isPostgres)
        {
            return $"{ValidateIdentifier(schema)}.\"WorkflowInstanceData\"";
        }

        if (isSqlServer)
        {
            var safeSchema = string.IsNullOrWhiteSpace(schema) ? "dbo" : schema;
            if (!SafeIdRegex.IsMatch(safeSchema))
            {
                throw new InvalidOperationException($"Invalid SQL identifier '{schema}'.");
            }

            return $"[{safeSchema}].[WorkflowInstanceData]";
        }

        if (isMySql)
        {
            return "`WorkflowInstanceData`";
        }

        return "\"WorkflowInstanceData\"";
    }

    private static string QuoteColumn(string name, bool isSqlServer, bool isMySql) =>
        isSqlServer ? $"[{name}]" : isMySql ? $"`{name}`" : $"\"{name}\"";

    private static string CleanIdentifier(string text) =>
        Regex.Replace(text, "[^A-Za-z0-9_]", "_");

    private static string ValidateIdentifier(string? name)
    {
        var safeName = string.IsNullOrWhiteSpace(name) ? "public" : name;
        return SafeIdRegex.IsMatch(safeName) ? $"\"{safeName}\"" : throw new InvalidOperationException($"Invalid SQL identifier '{name}'.");
    }
