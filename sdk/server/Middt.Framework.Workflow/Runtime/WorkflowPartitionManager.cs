    /// <summary>
    /// Ensures flow partitions and flow-specific indexes exist for all registered workflows.
    /// </summary>
    public static async Task EnsurePartitionsAndIndexesAsync(
        WorkflowDbContext db,
        WorkflowRegistry registry,
        string? schema,
        ILogger? logger,
        CancellationToken cancellationToken)
    {
        var provider = db.Database.ProviderName ?? string.Empty;
        var isPostgres = provider.Contains("Npgsql", StringComparison.Ordinal);
        var isSqlite = provider.Contains("Sqlite", StringComparison.Ordinal);

        if (!isPostgres && !isSqlite)
        {
            return;
        }

        var validatedSchema = isPostgres ? ValidateIdentifier(schema) : string.Empty;
        var isPartitioned = isPostgres && await IsPartitionedTableAsync(db, schema, "WorkflowInstances", cancellationToken);

        if (isPostgres && !isPartitioned)
        {
            var unpartitionedExists = await IsUnpartitionedTableAsync(db, schema, "WorkflowInstances", cancellationToken);
            if (unpartitionedExists)
            {
                await MigrateExistingTablesToPartitionedAsync(db, registry, schema, logger, cancellationToken);
                isPartitioned = true;
            }
        }

        if (isPostgres && isPartitioned)
        {
            await CreatePartitionedTablesAsync(db, schema, cancellationToken);
            await EnsureDefaultPartitionsAsync(db, validatedSchema, logger, cancellationToken);
        }

        foreach (var definition in registry.Latest)
        {
            var workflowKey = definition.Key;
            var suffix = PartitionSuffix(workflowKey);

            if (isPostgres && isPartitioned)
            {
                await EnsureFlowPartitionsAsync(db, validatedSchema, workflowKey, suffix, logger, cancellationToken);
            }

            await EnsureFlowIndexesAsync(db, definition, validatedSchema, suffix, isPostgres, isPartitioned, logger, cancellationToken);
        }

        if (isPostgres)
        {
            await EnsureGlobalIndexesAsync(db, validatedSchema, logger, cancellationToken);
        }
    }

